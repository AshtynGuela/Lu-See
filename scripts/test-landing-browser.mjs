import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { encodeSession } from '../src/share.mjs';
import { landingWindows } from '../engine/landing.mjs';
import { summarize, DAY } from '../engine/index.mjs';
import { arrivalSearch, DEFAULT_MISSION_PROFILE, flightEstimate } from '../engine/mission-history.mjs';
const shots='.impeccable/review/landing';
await fs.mkdir(shots,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'}), errors=[];
page.on('pageerror',e=>errors.push(e.message));
const state={scenarios:[],custom:[],mastM:2,minAntennaEl:5,time:Date.parse('2025-03-14T07:00:00Z'),selected:'apollo11',view:'globe',mode:'plain'};
try {
  await page.goto('http://127.0.0.1:5175/?session='+encodeURIComponent(encodeSession(state)));
  await page.getByRole('button',{name:'Skip introduction'}).click();
  await expect(page.locator('.condition-readings')).toContainText('Sunlight now',{timeout:150000});
  await expect(page.locator('.sunlight-reading')).toContainText("Earth's shadow");
  await page.screenshot({path:shots+'/dashboard-desktop.png'});
  await page.getByRole('button',{name:'Plan landing',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Plan a landing'});
  await expect(dialog.getByLabel('Arrival date and time',{exact:false})).toHaveCount(0);
  await expect(dialog).toContainText('Estimated flight 7 d 17 h');
  await page.getByText('Timing and historical sources',{exact:true}).click();
  await expect(page.getByRole('spinbutton',{name:/Surface duration/})).toHaveValue('7');
  await page.getByRole('spinbutton',{name:/Surface duration/}).fill('3');
  await page.getByLabel('Earliest departure',{exact:false}).fill('2025-02-22');
  await page.screenshot({path:shots+'/planner-desktop.png'});
  const response=page.waitForResponse(r=>r.url().includes('/api/ephemeris?')&&r.url().includes('2025-03-01')&&r.status()===200,{timeout:180000});
  await page.getByRole('button',{name:'Find possible landing dates',exact:true}).click();
  const packet=await(await response).json();
  assert.ok(packet.sources.every(s=>s.name==='NASA/JPL Horizons'&&s.sha256.length===64));
  await expect(page.locator('.landing-candidate').first()).toBeVisible({timeout:90000});
  await page.locator('.landing-results').scrollIntoViewIfNeeded();
  await page.screenshot({path:shots+'/results-desktop.png'});
  const terrain=await(await page.request.get('http://127.0.0.1:5175/api/terrain/apollo11')).json();
  const profile={minSunlitPct:80,maxDarknessHours:12,minEarthDtePct:60};
  const {start,end}=arrivalSearch(Date.parse('2025-02-22'),30,DEFAULT_MISSION_PROFILE);
  const result=landingWindows(packet,start,end,3,terrain.masks['2'],5,profile);
  const firstFlight=flightEstimate(result.windows[0].best.time,DEFAULT_MISSION_PROFILE);
  await expect(page.locator('.landing-candidate').first()).toContainText(firstFlight.departureUtc.slice(0,16).replace('T',' '));
  for(const w of result.windows) {
    const m=summarize(packet,w.best.time,3,terrain.masks['2'],5,0,[]);
    for(const k of ['sunlitPct','earthDtePct','longestDarkH']) assert.ok(Math.abs(m[k]-w.best[k])<1e-7,k);
  }
  // Changing limits clears previous choices, and an impossible eclipse-overlapping
  // 30-day mission cannot meet a zero-darkness requirement at Apollo 11.
  await page.getByRole('spinbutton',{name:/Surface duration/}).fill('30');
  await expect(page.locator('.landing-candidate')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Add to comparison',exact:true})).toBeDisabled();
  await page.getByRole('spinbutton',{name:/Minimum time in sunlight/}).fill('100');
  await page.getByRole('spinbutton',{name:/Longest allowed darkness/}).fill('0');
  await page.getByRole('button',{name:'Find possible landing dates',exact:true}).click();
  await expect(page.getByRole('heading',{name:'No dates meet these limits'})).toBeVisible({timeout:180000});
  await page.screenshot({path:shots+'/no-results-desktop.png'});
  await page.getByRole('spinbutton',{name:/Surface duration/}).fill('3');
  await page.getByRole('spinbutton',{name:/Minimum time in sunlight/}).fill('80');
  await page.getByRole('spinbutton',{name:/Longest allowed darkness/}).fill('12');
  await page.getByRole('button',{name:'Find possible landing dates',exact:true}).click();
  await expect(page.locator('.landing-candidate').first()).toBeVisible({timeout:90000});
  await page.setViewportSize({width:390,height:844});
  await dialog.evaluate(el=>el.scrollTop=0);
  await page.screenshot({path:shots+'/planner-mobile.png'});
  await page.locator('.landing-results').scrollIntoViewIfNeeded();
  await page.screenshot({path:shots+'/results-mobile.png'});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.getByRole('button',{name:'Add to comparison',exact:true}).click();
  await expect(page.getByRole('heading',{name:/Compare landing scenarios/})).toBeVisible();
  await expect(page.locator('.comparison-values')).not.toContainText('Loading',{timeout:30000});
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('lunar-scouter-v1')).state.scenarios[0]);
  assert.equal(Date.parse(saved.epoch),result.windows[0].best.time);
  assert.equal(saved.flightProfile,DEFAULT_MISSION_PROFILE);
  await page.getByRole('button',{name:'Close comparison'}).click();
  await expect(page.locator('.mission-verdict')).toContainText('Meets your');
  await page.locator('.inspector').evaluate(e=>e.scrollTop=0);
  await page.screenshot({path:shots+'/dashboard-mobile.png'});
  await page.locator('.condition-readings').scrollIntoViewIfNeeded();
  await page.screenshot({path:shots+'/conditions-mobile.png'});
  await page.getByRole('heading',{name:'Over your whole mission'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:shots+'/mission-mobile.png'});
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('heading',{name:'Over your whole mission'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:shots+'/mission-desktop.png'});
  assert.deepEqual(errors,[]);
  const report={testedUtc:new Date().toISOString(),realApi:true,candidateWindows:result.windows,selectedScenario:saved,emptyState:true,staleResultsCleared:true,mobile:true,errors};
  await fs.writeFile('data/validation/landing-browser.json',JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
} finally {await browser.close();}
